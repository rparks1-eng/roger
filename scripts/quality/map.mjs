import { renderExplorer } from './explorer.mjs';
import { createImportMap } from './import-map.mjs';
// Rebuild one bounded, source-derived import map; never copy source text.
import { spawnSync } from 'node:child_process';
import { readFile, readdir, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('../../', import.meta.url));
process.chdir(root);
function capture(command, args) {
  const result = spawnSync(command, args, {
    cwd: root,
    encoding: 'utf8',
    timeout: 30_000,
    maxBuffer: 4 * 1024 * 1024,
  });
  if (result.error || result.status !== 0)
    throw result.error || new Error(result.stderr || 'Architecture extraction failed.');
  return JSON.parse(result.stdout);
}
const javascript = capture(process.execPath, [
  'node_modules/dependency-cruiser/bin/dependency-cruiser.mjs',
  'src',
  '--config',
  '.dependency-cruiser.cjs',
  '--output-type',
  'json',
]);
if (javascript.summary.error)
  throw new Error('Architecture rules failed; see npm run check:architecture.');
const python = capture(
  process.platform === 'win32' ? '.venv/Scripts/python.exe' : '.venv/bin/python',
  ['-B', 'scripts/quality/python-architecture.py'],
);
const nodes = new Set(python.modules);
const edges = [...python.edges];
const jsProvenance = createImportMap(javascript, {
  root,
  include: (file) => file.startsWith('src/'),
});
for (const module of jsProvenance.modules) {
  nodes.add(module.file);
  for (const dependency of module.dependencies)
    edges.push({
      from: module.file,
      to: dependency.to,
      kind: 'js-import',
      locations: dependency.locations,
      locationStatus: dependency.locationStatus,
    });
}
const declarations = JSON.parse(await readFile('architecture-bridges.json', 'utf8'));
for (const [from, to, literal] of declarations) {
  const source = await readFile(from, 'utf8');
  const line = source.split('\n').findIndex((value) => value.includes(literal)) + 1;
  if (!line) throw new Error(`Declared worker reference changed: ${from}`);
  edges.push({ from, to, kind: 'declared-worker', line });
}
const sha = (data) => createHash('sha256').update(data).digest('hex');
const sources = [];
async function walk(directory) {
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    if (entry.isSymbolicLink() || entry.name.startsWith('.')) continue;
    const name = path.posix.join(directory, entry.name);
    if (entry.isDirectory()) await walk(name);
    else if (/\.(mjs|ts|py)$/.test(name))
      sources.push({ path: name, sha256: sha(await readFile(name)) });
  }
}
await walk('src');
sources.sort((a, b) => a.path.localeCompare(b.path));
edges.sort((a, b) => JSON.stringify(a).localeCompare(JSON.stringify(b)));
const map = {
  schema: 2,
  jsProvenance,
  coverage:
    'JavaScript/TypeScript and Python static imports plus verified worker declarations; no runtime data lineage or provider reachability claim.',
  fingerprint: sha(JSON.stringify(sources)),
  sources,
  nodes: [...nodes].sort(),
  edges,
};
const ids = new Map(map.nodes.map((name, index) => [name, `n${index}`]));
const mermaid = [
  'flowchart LR',
  ...map.nodes.map((name) => `  ${ids.get(name)}["${name}"]`),
  ...edges
    .filter((edge) => ids.has(edge.from) && ids.has(edge.to))
    .map((edge) => `  ${ids.get(edge.from)} -->|${edge.kind}| ${ids.get(edge.to)}`),
];
const md =
  '# Reader code relationships\n\n[Open the interactive visual map](Explorer.html).\n\nGenerated by `npm run map`; refreshed automatically by normal checks/start.\nDo not edit by hand. Edges show source dependencies and declared workers, not runtime data flow.\n\n```mermaid\n' +
  mermaid.join('\n') +
  '\n```\n\n## Open source\n\n' +
  map.nodes.map((name) => `- [${name}](../${name})`).join('\n') +
  '\n\n## Import evidence\n\n| Caller | Dependency | Source line |\n|---|---|---|\n' +
  map.edges
    .map(
      (edge) =>
        `| [${edge.from}](../${edge.from}) | ${edge.to} | ${edge.line || edge.locations?.map((site) => site.line).join(', ') || edge.locationStatus || 'unknown; no parsed location'} |`,
    )
    .join('\n') +
  '\n\nThe JSON includes exact source hashes, dependency-lock and producer identity, reverse importers, external import syntax and explicit dynamic/unsupported unknowns.\n';
const outputs = {
  'architecture/source-map.json': JSON.stringify(map, null, 2) + '\n',
  'architecture/Code Map.md': md,
  'architecture/Explorer.html': renderExplorer(map),
};
if (process.argv.includes('--check')) {
  for (const [name, expected] of Object.entries(outputs))
    if ((await readFile(name, 'utf8').catch(() => null)) !== expected)
      throw new Error(`Stale architecture output: ${name}. Run npm run map.`);
} else {
  await mkdir('architecture', { recursive: true });
  for (const [name, output] of Object.entries(outputs))
    if ((await readFile(name, 'utf8').catch(() => null)) !== output) await writeFile(name, output);
}
console.log(
  `Source map: ${map.nodes.length} modules, ${edges.length} relationships; runtime/dynamic connections remain unknown.`,
);
